function getAgeBracketKey(age: number): {
  key: string;
  range: [number, number];
  label: string;
} {
  if (age <= 23) return { key: "18_23", range: [18, 23], label: "18–23 thn" };
  if (age <= 28) return { key: "24_28", range: [24, 28], label: "24–28 thn" };
  if (age <= 33) return { key: "29_33", range: [29, 33], label: "29–33 thn" };
  if (age <= 38) return { key: "34_38", range: [34, 38], label: "34–38 thn" };
  return { key: "39_45", range: [39, 45], label: "39–45 thn" };
}

export function build20QuestionsForProfile(
  gender: "Laki-laki" | "Perempuan",
  age: number
): QuestionItem[] {
  const genderPrefix = gender === "Laki-laki" ? "M" : "F";
  const bracket = getAgeBracketKey(age);
  const segKey = `${genderPrefix}_${bracket.key}`;
  const rawList = SEGMENT_DATA[segKey] || SEGMENT_DATA["M_24_28"];

  const catMap: Record<RawQuestionTuple["cat"], QuestionItem["category"]> = {
    KH: "Ketakutan Hidup",
    KB: "Kebiasaan Buruk",
    SJ: "Sifat Jelek & Red Flag Ego",
  };

  return rawList.map((item, idx) => ({
    id: `${segKey}_${idx + 1}`,
    category: catMap[item.cat],
    gender,
    ageRange: bracket.range,
    segmentLabel: `${gender} • ${bracket.label}`,
    statement: item.s,
    partnerPrompt: item.p,
    consequenceQuestion: item.c,
    compromises: item.opt,
    botPref: {
      young: item.pref[0],
      mid: item.pref[1],
      mature: item.pref[2],
    },
  }));
}
